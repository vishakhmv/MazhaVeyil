// Generates ../contracts/cliffMath.js: a dependency-free browser module with the VERIFIED KSEB table and the cliff-meter maths,
// returning exactly the variable names the Cliff Meter page already uses. Generated from rules.json so it cannot drift from the engine.
// Usage: npm run cliffmath
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ENGINE_ROOT, loadRules } from '../src/rules.js';

const rules = loadRules();
const t = rules.tariffs[0];
const table = { id: t.id, valid_from: t.valid_from, valid_to: t.valid_to, telescopic: t.telescopic_up_to_250, flat: t.flat_all_units_above_250 };
const unitsPerKw = rules.solar.units_per_kw_month_rule;
const duty = rules.bill_extras.electricity_duty_pct_of_energy;

const code = `// GENERATED by engine/scripts/make-cliffmath.js from engine/rules/rules.json. Do not edit by hand: run npm --prefix engine run cliffmath.
// KSEB LT-1A domestic tariff, verified against kseb.in on ${rules.checked_on}. Slabs are per MONTH; a 2-month bill is judged on units/2.
// Energy + fixed charge + ${duty}% electricity duty on the energy charge. The fuel surcharge and meter rent are not modelled.

export const TARIFF = ${JSON.stringify(table, null, 2)};
export const SOLAR_UNITS_PER_KW_MONTH = ${unitsPerKw};
export const DUTY_PCT = ${duty};

const SLAB_LIMIT = TARIFF.telescopic[TARIFF.telescopic.length - 1].upto;
const paise = (r) => Math.round(r * 100);

// Energy charge in rupees for ONE month of m units.
export function monthEnergy(m) {
  if (!(m > 0)) return 0;
  if (m <= SLAB_LIMIT) {
    let lo = 0;
    let total = 0;
    for (const s of TARIFF.telescopic) {
      if (m > lo) total += (Math.min(m, s.upto) - lo) * paise(s.rate);
      lo = s.upto;
    }
    return Math.round(total) / 100;
  }
  const band = TARIFF.flat.find((b) => m <= b.upto) || TARIFF.flat[TARIFF.flat.length - 1];
  return Math.round(m * paise(band.rate)) / 100;
}

// Fixed charge in rupees for ONE month (single phase unless phase is '3ph').
export function monthFixed(m, phase = '1ph') {
  const row = m <= SLAB_LIMIT ? TARIFF.telescopic.find((s) => m <= s.upto) || TARIFF.telescopic[0] : TARIFF.flat.find((b) => m <= b.upto) || TARIFF.flat[TARIFF.flat.length - 1];
  return phase === '3ph' ? row.fixed_3ph : row.fixed_1ph;
}

// One whole bill (1 or 2 months): { energy, fixed, duty, total, rate }.
export function bill(units, months = 1, phase = '1ph') {
  const m = units / months;
  const energy = months * monthEnergy(m);
  const fixed = months * monthFixed(m, phase);
  const d = Math.round(energy * DUTY_PCT) / 100;
  const band = m <= SLAB_LIMIT ? null : TARIFF.flat.find((b) => m <= b.upto) || TARIFF.flat[TARIFF.flat.length - 1];
  return { energy, fixed, duty: d, total: Math.round(energy + fixed + d), rate: band ? band.rate : null };
}

// The cliffs: the units where the next unit makes every unit dearer, with the jump in energy charge.
export function cliffs() {
  const bounds = [SLAB_LIMIT, ...TARIFF.flat.filter((b) => b.upto < 99999).map((b) => b.upto)];
  return bounds.map((at) => ({ at, jump: Math.round((monthEnergy(at + 1) - monthEnergy(at)) * 100) / 100 }));
}

// Drop-in for CliffMeter.jsx: same variable names the page already renders, on a 2-month bill.
export function cliffMeterNumbers(bimonthlyUnits, solarCapacityKw) {
  const monthlyUnits = bimonthlyUnits / 2;
  const without = bill(bimonthlyUnits, 2);
  const solarGenBimonthly = Math.round(solarCapacityKw * SOLAR_UNITS_PER_KW_MONTH * 2);
  const netUnitsWithSolar = Math.max(0, bimonthlyUnits - solarGenBimonthly);
  const monthlyUnitsWithSolar = netUnitsWithSolar / 2;
  const withSolar = bill(netUnitsWithSolar, 2);
  return {
    monthlyUnits,
    isCliffTriggered: monthlyUnits > SLAB_LIMIT,
    rawEnergyCostWithoutSolar: without.energy,
    fixedChargeWithoutSolar: without.fixed,
    fuelSurchargeWithout: 0,
    dutyWithout: without.duty,
    totalBillWithoutSolar: without.total,
    solarGenBimonthly,
    netUnitsWithSolar,
    monthlyUnitsWithSolar,
    isCliffTriggeredWithSolar: monthlyUnitsWithSolar > SLAB_LIMIT,
    rawCostWithSolar: withSolar.energy,
    fixedChargeWithSolar: netUnitsWithSolar === 0 ? 0 : withSolar.fixed,
    dutyWith: withSolar.duty,
    totalBillWithSolar: netUnitsWithSolar === 0 ? 0 : withSolar.total,
    netSavings: Math.max(0, without.total - (netUnitsWithSolar === 0 ? 0 : withSolar.total)),
  };
}
`;
writeFileSync(join(ENGINE_ROOT, '..', 'contracts', 'cliffMath.js'), code);
console.log('wrote contracts/cliffMath.js (' + code.length + ' bytes)');
